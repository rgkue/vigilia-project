export function makeDemoEvent(demoCase: DemoCase): IngressEvent {
  const stamp = Date.now().toString(36).toUpperCase();
  return {
    evento_id: `ING-DEMO-${stamp}`,
    cedula: demoCase.insuredId,
    hospital: demoCase.hospitalName,
    motivo_ingreso: demoCase.reason,
    ...(demoCase.triage === undefined ? {} : { triage: demoCase.triage }),
    fecha_ingreso: new Date().toISOString(),
  };
}

export function makeLocalResult(event: IngressEvent, demoCase: DemoCase): AgentResponse {
  return {
    event_id: event.evento_id,
    created_at: event.fecha_ingreso,
    administrative_level: demoCase.alertLevel,
    verdict: demoCase.verdict,
    summary: demoCase.summary,
    policy: {
      number: null,
      plan: null,
      status: demoCase.policyStatus,
      explanation: demoCase.policyExplanation,
    },
    preexisting: {
      match: demoCase.preexistingMatch,
      explanation: demoCase.preexistingExplanation,
    },
    classifications: [],
    messages: {
      admissions: demoCase.messageAdmissions,
      case_manager: demoCase.messageCaseManager,
    },
    notifications: {
      admissions: { status: "simulated", channel: "demo local" },
      case_manager: { status: "simulated", channel: "demo local" },
    },
    integrations: [],
    source: "local_demo",
  };
}
